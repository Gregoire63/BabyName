/** Polski : trzy formy liczby mnogiej (one / few / many). */
const REGULY = new Intl.PluralRules('pl')
const lm = (n: unknown, one: string, few: string, many: string): string => {
  // Un nombre déjà formaté (« 1 234 », « 2,5 ») reste lisible.
  const x = typeof n === 'number' ? n : Number(String(n).replace(/[\s  ]/g, '').replace(',', '.'))
  const k = REGULY.select(x)
  return k === 'one' ? one : k === 'many' ? many : few
}

